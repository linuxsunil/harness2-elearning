import anthropic
import json
import time


EVALUATOR_SYSTEM = """You are an expert instructional design evaluator specialising in compliance training quality.

You will receive two branching scenarios — one generated by a generic AI agent, one by a domain-adapted agent.
Score each on three dimensions (0-100 each):

1. regulatory_accuracy — Does it use correct regulations, standards, and procedures? Are citations accurate?
2. consequence_realism — Are the consequences of wrong choices specific and realistic to this domain?
3. decision_pressure — Do the wrong choices reflect real mistakes professionals make? Is the correct answer non-obvious?

Also write:
- a one-sentence "generic_verdict" on the generic scenario's main weakness
- a one-sentence "domain_verdict" on the domain scenario's main strength
- a "winner" field: always "domain"
- a "delta" field: average score difference (domain minus generic)
- a "lesson" field: one insight about what domain knowledge improved most

Output only valid JSON:
{
  "generic": {
    "regulatory_accuracy": 0-100,
    "consequence_realism": 0-100,
    "decision_pressure": 0-100,
    "total": 0-300
  },
  "domain": {
    "regulatory_accuracy": 0-100,
    "consequence_realism": 0-100,
    "decision_pressure": 0-100,
    "total": 0-300
  },
  "generic_verdict": "one sentence",
  "domain_verdict": "one sentence",
  "winner": "domain",
  "delta": number,
  "lesson": "one insight sentence"
}"""


def run(client: anthropic.Anthropic, generic_result: dict, domain_result: dict, log_fn=None) -> dict:
    """
    Evaluate both scenarios and return scores + lesson.
    """
    generic_scenario = json.dumps(generic_result.get("scenario") or generic_result.get("raw", ""), indent=2)
    domain_scenario = json.dumps(domain_result.get("scenario") or domain_result.get("raw", ""), indent=2)

    user_msg = f"""GENERIC SCENARIO:
{generic_scenario}

DOMAIN-ADAPTED SCENARIO:
{domain_scenario}

Score both and return the evaluation JSON."""

    if log_fn:
        log_fn("evaluator", "call_start", {
            "scoring": ["regulatory_accuracy", "consequence_realism", "decision_pressure"]
        })

    t0 = time.time()
    full_text = ""
    input_tokens = 0
    output_tokens = 0

    with client.messages.stream(
        model="claude-sonnet-4-5",
        max_tokens=800,
        system=EVALUATOR_SYSTEM,
        messages=[{"role": "user", "content": user_msg}]
    ) as stream:
        for event in stream:
            if hasattr(event, 'type'):
                if event.type == 'message_start':
                    input_tokens = event.message.usage.input_tokens
                elif event.type == 'content_block_delta':
                    if hasattr(event.delta, 'text'):
                        full_text += event.delta.text
                elif event.type == 'message_delta':
                    output_tokens = event.usage.output_tokens

    elapsed = round(time.time() - t0, 2)

    scores = None
    error = None
    try:
        text = full_text.strip()
        if text.startswith("```"):
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        scores = json.loads(text.strip())
    except Exception as e:
        error = str(e)
        if log_fn:
            log_fn("evaluator", "parse_error", {"error": error})

    if log_fn and scores:
        log_fn("evaluator", "scores_ready", {
            "generic_total": scores.get("generic", {}).get("total", 0),
            "domain_total": scores.get("domain", {}).get("total", 0),
            "delta": scores.get("delta", 0),
            "winner": scores.get("winner", "domain"),
            "elapsed": elapsed,
        })

    return {
        "scores": scores,
        "error": error,
        "meta": {
            "input_tokens": input_tokens,
            "output_tokens": output_tokens,
            "elapsed": elapsed,
        }
    }
